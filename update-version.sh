#!/bin/sh
set -eu

usage() {
    printf 'Usage: sh %s <version> | --check [tag]\n' "$0" >&2
    exit 1
}

sdk_dir=$(CDPATH= cd "$(dirname "$0")" && pwd)
cd "$sdk_dir"
mode=${1:-}

render_source() {
    printf '%s\n' '# Code generated by update-version.sh. Do not edit.' "VERSION = \"$version\""
}

if [ "$mode" = "--check" ]; then
    shift
    [ "$#" -le 1 ] || usage
    version=$(poetry version --short)
    if [ "$#" -eq 1 ] && [ "${1#v}" != "$version" ]; then
        printf 'Release tag %s does not match pyproject.toml (%s)\n' "$1" "$version" >&2
        exit 1
    fi
else
    [ "$#" -eq 1 ] || usage
    version=${1#v}
    case "$version" in
        *[!0-9A-Za-z.!+_-]*) printf 'Invalid SDK version\n' >&2; exit 1 ;;
    esac
    if ! printf '%s\n' "$version" | grep -Eq '^([0-9]+!)?[0-9]+\.[0-9]+\.[0-9]+[0-9A-Za-z.+_-]*$'; then
        printf 'Invalid SDK version\n' >&2
        exit 1
    fi
    poetry version "$version"
    version=$(poetry version --short)
fi

if [ "$mode" = "--check" ]; then
    if ! printf '%s\n' "$version" | cmp -s VERSION - || ! render_source | cmp -s saasus_sdk_python/_version.py -; then
        printf 'VERSION or Python constant does not match pyproject.toml (%s)\n' "$version" >&2
        exit 1
    fi
else
    printf '%s\n' "$version" > VERSION
    render_source > saasus_sdk_python/_version.py
fi
